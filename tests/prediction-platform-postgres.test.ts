// @vitest-environment node
import { readFileSync } from 'node:fs'
import { PGlite } from '@electric-sql/pglite'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'

const migration = readFileSync('supabase/migrations/20260815123000_build_prediction_competitions.sql', 'utf8')
const geographyMigration = readFileSync('supabase/migrations/20260815133000_prediction_geography_and_immediate_leagues.sql', 'utf8')
const marketLeagueMigration = readFileSync('supabase/migrations/20260809152000_create_market_friend_leagues.sql', 'utf8')
const expansionMigration = readFileSync('supabase/migrations/20260815150000_expand_competition_worlds.sql', 'utf8')
const db = new PGlite()
const owner = '10000000-0000-4000-8000-000000000001'
const friend = '10000000-0000-4000-8000-000000000002'

beforeAll(async () => {
  await db.exec(`
    create role anon nologin; create role authenticated nologin; create role service_role nologin;
    create schema auth;
    create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    create table public.profiles(id uuid primary key references auth.users(id),username text);
    create table public.predictions(
      id bigint generated by default as identity primary key,
      user_id uuid not null references auth.users(id),prediction_set text not null,fixture_id text not null,
      home_team text not null,away_team text not null,pick text not null,
      created_at timestamptz not null default now(),updated_at timestamptz not null default now(),
      unique(user_id,prediction_set,fixture_id)
    );
    create policy "Users can insert own predictions" on public.predictions for insert to authenticated with check(auth.uid()=user_id);
    create policy "Users can update own predictions" on public.predictions for update to authenticated using(auth.uid()=user_id);
    create table public.market_store_items(item_key text primary key,description text not null);
    create table public.market_reward_wallets(user_id uuid primary key references auth.users(id),balance integer not null default 0,lifetime_earned integer not null default 0,updated_at timestamptz not null default now());
    create table public.quiz_results(id bigint generated by default as identity primary key,user_id uuid references auth.users(id),quiz_id text not null,score integer not null,total integer not null,xp_earned integer not null,completed_at timestamptz not null default now());
    create table public.market_portfolios(id bigint generated by default as identity primary key,user_id uuid unique references auth.users(id),total_portfolio_value_minor bigint not null default 100000000,realised_profit_minor bigint not null default 0,current_holdings_value_minor bigint not null default 0);
    create view public.market_public_leaderboard as select id portfolio_id,user_id,0::bigint weekly_change_minor from public.market_portfolios;
    insert into public.market_store_items values
      ('title_early_adopter','broken'),('title_value_hunter','broken'),('title_market_mind','broken'),('title_club_legend','broken');
    insert into auth.users values('${owner}'),('${friend}'),
      ('10000000-0000-4000-8000-000000000003'),('10000000-0000-4000-8000-000000000004'),
      ('10000000-0000-4000-8000-000000000005'),('10000000-0000-4000-8000-000000000006');
    insert into public.profiles values('${owner}','First Shout'),('${friend}','Second Shout'),
      ('10000000-0000-4000-8000-000000000003','Third Shout'),('10000000-0000-4000-8000-000000000004','Fourth Shout'),
      ('10000000-0000-4000-8000-000000000005','Fifth Shout'),('10000000-0000-4000-8000-000000000006','Sixth Shout');
  `)
  await db.exec(migration)
  await db.exec(geographyMigration)
  await db.exec(marketLeagueMigration)
  await db.exec(expansionMigration)
})

afterAll(async () => db.close())

describe('prediction competition database boundary', () => {
  it('repairs human-facing reward copy and installs protected competition tables', async () => {
    const title = await db.query<{ description: string }>(`select description from public.market_store_items where item_key='title_early_adopter'`)
    expect(title.rows[0]?.description).toBe('Show "Founder Beta" beneath your username.')
    const tables = await db.query<{ count: number }>(`select count(*)::int count from information_schema.tables where table_schema='public' and table_name like 'prediction_%'`)
    expect(tables.rows[0]?.count).toBeGreaterThanOrEqual(5)
  })

  it('creates a friend league, joins by code and keeps the owner in charge', async () => {
    await db.exec(`select set_config('request.jwt.claim.sub','${owner}',false)`)
    const created = await db.query<{ result: { id: string; league_code: string } }>(`select public.prediction_create_league('Weekend Crew','random_5',array['premier-league','la-liga']) result`)
    const league = created.rows[0]!.result
    expect(league.league_code).toMatch(/^[A-Z0-9]{8}$/)

    await db.exec(`select set_config('request.jwt.claim.sub','${friend}',false)`)
    await db.query(`select public.prediction_join_league($1)`, [league.league_code])
    const members = await db.query<{ count: number }>(`select count(*)::int count from public.prediction_league_members where league_id=$1`, [league.id])
    expect(members.rows[0]?.count).toBe(2)

    await db.exec(`select set_config('request.jwt.claim.sub','${owner}',false)`)
    await expect(db.query(`select public.prediction_leave_league($1)`, [league.id])).rejects.toThrow('OWNER_CANNOT_LEAVE')
  })

  it('installs 24 quiz rooms and supports configurable quiz and market friend tables', async () => {
    const catalogue = await db.query<{ count:number }>('select count(*)::int count from public.quiz_league_catalogue')
    expect(catalogue.rows[0]?.count).toBe(24)

    await db.exec(`select set_config('request.jwt.claim.sub','${owner}',false)`)
    const quiz = await db.query<{result:{id:string;league_code:string}}>(`select public.quiz_create_friend_league('World Brains','league_world','accuracy','weekly',array['premier-league','championship','league-one','league-two']) result`)
    const quizLeague=quiz.rows[0]!.result
    await db.exec(`insert into public.quiz_results(user_id,quiz_id,score,total,xp_earned) values('${owner}','league-world-premier-league',4,5,60)`)
    const quizTable=await db.query<{accuracy_percent:number;quizzes_completed:number}>(`select accuracy_percent,quizzes_completed from public.quiz_get_friend_league_leaderboard('${quizLeague.id}')`)
    expect(Number(quizTable.rows[0]?.accuracy_percent)).toBe(80)
    expect(quizTable.rows[0]?.quizzes_completed).toBe(1)

    const market=await db.query<{result:{id:number;score_mode:string}}>(`select public.market_create_friend_league('Weekly Movers','weekly_gain') result`)
    expect(market.rows[0]?.result.score_mode).toBe('weekly_gain')
  })

  it('accepts future picks through the server RPC, then locks them at kickoff', async () => {
    await db.exec(`
      insert into public.prediction_fixtures(fixture_id,league_key,league_name,gameweek_key,home_team,away_team,kickoff_at,is_derby)
      values('future-1','premier-league','Premier League','2026-34','Arsenal','Tottenham',now()+interval '1 day',true);
      select set_config('request.jwt.claim.sub','${owner}',false);
    `)
    const saved = await db.query<{ result: { saved: number } }>(`select public.prediction_save_picks('[{"fixture_id":"future-1","pick":"home","confidence":4}]') result`)
    expect(saved.rows[0]?.result.saved).toBe(1)
    await db.exec(`update public.prediction_fixtures set kickoff_at=now()-interval '1 minute' where fixture_id='future-1'`)
    await expect(db.query(`select public.prediction_save_picks('[{"fixture_id":"future-1","pick":"away","confidence":5}]')`)).rejects.toThrow('PICKS_LOCKED')
  })

  it('scores results once and awards derby plus crowd-difficulty bonuses on the server', async () => {
    await db.exec(`
      update public.prediction_fixtures set status='completed',home_score=2,away_score=1 where fixture_id='future-1';
      update public.predictions set created_at=now()-interval '1 hour' where fixture_id='future-1' and user_id='${owner}';
      insert into public.predictions(user_id,prediction_set,fixture_id,home_team,away_team,pick,confidence,created_at)
      values('${friend}','2026-34','future-1','Arsenal','Tottenham','away',3,now()-interval '1 hour');
      insert into public.predictions(user_id,prediction_set,fixture_id,home_team,away_team,pick,confidence,created_at)
      select id,'2026-34','future-1','Arsenal','Tottenham','away',3,now()-interval '1 hour'
      from auth.users where id not in('${owner}','${friend}');
    `)
    const first = await db.query<{ result: { fixtures_scored: number } }>('select public.prediction_score_completed_fixtures() result')
    expect(first.rows[0]?.result.fixtures_scored).toBe(1)
    const scores = await db.query<{ user_id: string; points_awarded: number }>(`select user_id::text,points_awarded from public.predictions where fixture_id='future-1' order by user_id`)
    expect(scores.rows.find((row) => row.user_id === owner)?.points_awarded).toBe(6)
    expect(scores.rows.filter((row) => row.user_id !== owner).every((row) => row.points_awarded === 0)).toBe(true)
    const retry = await db.query<{ result: { fixtures_scored: number } }>('select public.prediction_score_completed_fixtures() result')
    expect(retry.rows[0]?.result.fixtures_scored).toBe(0)
  })

  it('uses only player-chosen location for country and continent tables', async () => {
    await db.exec(`select set_config('request.jwt.claim.sub','${owner}',false)`)
    await db.query(`select public.prediction_set_location('BE','EU',true)`)
    const belgium = await db.query<{ username: string }>(`select username from public.prediction_get_public_leaderboard('all','country','BE')`)
    expect(belgium.rows.map((row) => row.username)).toEqual(['First Shout'])
    const spain = await db.query<{ username: string }>(`select username from public.prediction_get_public_leaderboard('all','country','ES')`)
    expect(spain.rows).toEqual([])
  })
})
