-- Admin-safe price update command with preview mode.
-- This function is intentionally restricted to service_role JWT context.
drop function if exists public.market_admin_update_player_value(text, bigint, text, text, boolean);
create or replace function public.market_admin_update_player_value(
  p_player_slug text,
  p_new_value bigint,
  p_reason_category text,
  p_methodology_version text,
  p_apply boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  jwt_role text := coalesce(auth.jwt() ->> 'role', 'anon');
  player_row public.market_players;
  rounded_value bigint;
  delta bigint;
begin
  if jwt_role <> 'service_role' then
    raise exception 'Forbidden: service role required';
  end if;

  if p_new_value < 0 then
    raise exception 'Invalid value';
  end if;

  select * into player_row
  from public.market_players
  where slug = p_player_slug
  for update;

  if player_row.id is null then
    raise exception 'Player not found';
  end if;

  rounded_value := (round(p_new_value::numeric / 100000) * 100000)::bigint;
  delta := rounded_value - player_row.current_value;

  if p_apply then
    update public.market_players
    set
      previous_value = player_row.current_value,
      current_value = rounded_value,
      value_updated_at = now()
    where id = player_row.id;

    insert into public.market_value_history(player_id, value, reason_category, methodology_version)
    values (player_row.id, rounded_value, p_reason_category, p_methodology_version);

    update public.market_settings
    set
      methodology_version = p_methodology_version,
      last_market_update_at = now()
    where singleton = true;
  end if;

  return jsonb_build_object(
    'ok', true,
    'applied', p_apply,
    'player_slug', p_player_slug,
    'previous_value', player_row.current_value,
    'new_value', rounded_value,
    'delta', delta,
    'reason_category', p_reason_category,
    'methodology_version', p_methodology_version
  );
end;
$$;

-- Public-safe leaderboard view for Player Market only.
create or replace view public.market_public_leaderboard as
with baseline as (
  select
    p.user_id,
    p.starting_balance,
    p.total_account_value,
    p.total_account_value - p.starting_balance as all_time_gain,
    (now() at time zone 'UTC')::date as today_utc
  from public.market_portfolios p
),
windows as (
  select
    b.user_id,
    b.starting_balance,
    b.total_account_value,
    b.all_time_gain,
    b.today_utc,
    (b.today_utc - 1) as daily_start,
    (b.today_utc - 7) as weekly_start,
    date_trunc('month', b.today_utc)::date as monthly_start,
    make_date(extract(year from b.today_utc)::int, (((extract(quarter from b.today_utc)::int - 1) * 3) + 1), 1) as season_start
  from baseline b
),
joined as (
  select
    w.user_id,
    w.total_account_value,
    w.starting_balance,
    w.all_time_gain,
    coalesce((select s.total_account_value from public.market_portfolio_snapshots s where s.user_id = w.user_id and s.snapshot_date = w.daily_start), w.starting_balance) as daily_base,
    coalesce((select s.total_account_value from public.market_portfolio_snapshots s where s.user_id = w.user_id and s.snapshot_date >= w.weekly_start order by s.snapshot_date asc limit 1), w.starting_balance) as weekly_base,
    coalesce((select s.total_account_value from public.market_portfolio_snapshots s where s.user_id = w.user_id and s.snapshot_date >= w.monthly_start order by s.snapshot_date asc limit 1), w.starting_balance) as monthly_base,
    coalesce((select s.total_account_value from public.market_portfolio_snapshots s where s.user_id = w.user_id and s.snapshot_date >= w.season_start order by s.snapshot_date asc limit 1), w.starting_balance) as season_base
  from windows w
)
select
  pr.id as user_id,
  pr.username,
  j.total_account_value,
  j.all_time_gain,
  (j.total_account_value - j.daily_base) as daily_gain,
  (j.total_account_value - j.weekly_base) as weekly_gain,
  (j.total_account_value - j.monthly_base) as monthly_gain,
  (j.total_account_value - j.season_base) as season_gain,
  case when j.daily_base > 0 then round(((j.total_account_value - j.daily_base)::numeric / j.daily_base::numeric) * 100, 2) else 0 end as daily_return_pct,
  case when j.weekly_base > 0 then round(((j.total_account_value - j.weekly_base)::numeric / j.weekly_base::numeric) * 100, 2) else 0 end as weekly_return_pct,
  case when j.monthly_base > 0 then round(((j.total_account_value - j.monthly_base)::numeric / j.monthly_base::numeric) * 100, 2) else 0 end as monthly_return_pct,
  case when j.season_base > 0 then round(((j.total_account_value - j.season_base)::numeric / j.season_base::numeric) * 100, 2) else 0 end as season_return_pct,
  case when j.starting_balance > 0 then round((j.all_time_gain::numeric / j.starting_balance::numeric) * 100, 2) else 0 end as all_time_return_pct
from joined j
join public.profiles pr on pr.id = j.user_id
where pr.username is not null;

grant select on public.market_public_leaderboard to anon;
grant select on public.market_public_leaderboard to authenticated;

