-- Internal helper: create/get portfolio row.
create or replace function public.market_ensure_portfolio(p_user_id uuid)
returns public.market_portfolios
language plpgsql
security definer
set search_path = public
as $$
declare
  p public.market_portfolios;
begin
  insert into public.market_portfolios(user_id)
  values (p_user_id)
  on conflict (user_id) do nothing;

  select * into p
  from public.market_portfolios
  where user_id = p_user_id;

  return p;
end;
$$;

-- Internal helper: refresh holding snapshots + portfolio totals.
create or replace function public.market_recalculate_portfolio_totals(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  current_portfolio_value bigint := 0;
  current_total_value bigint := 0;
  current_balance bigint := 0;
begin
  update public.market_holdings h
  set
    current_value_snapshot = p.current_value,
    unrealized_profit_loss = p.current_value - h.acquisition_value
  from public.market_players p
  where h.player_id = p.id
    and h.user_id = p_user_id;

  select coalesce(sum(h.current_value_snapshot), 0)
  into current_portfolio_value
  from public.market_holdings h
  where h.user_id = p_user_id;

  select available_balance
  into current_balance
  from public.market_portfolios
  where user_id = p_user_id;

  current_total_value := current_balance + current_portfolio_value;

  update public.market_portfolios
  set
    portfolio_value = current_portfolio_value,
    total_account_value = current_total_value
  where user_id = p_user_id;
end;
$$;

-- Internal helper: snapshot today.
create or replace function public.market_capture_snapshot(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  d date := (now() at time zone 'UTC')::date;
  p public.market_portfolios;
begin
  select * into p
  from public.market_portfolios
  where user_id = p_user_id;

  if p.user_id is null then
    return;
  end if;

  insert into public.market_portfolio_snapshots(
    user_id, snapshot_date, available_balance, portfolio_value, total_account_value
  )
  values (p.user_id, d, p.available_balance, p.portfolio_value, p.total_account_value)
  on conflict (user_id, snapshot_date)
  do update set
    available_balance = excluded.available_balance,
    portfolio_value = excluded.portfolio_value,
    total_account_value = excluded.total_account_value,
    created_at = now();
end;
$$;

-- Internal helper: one-time XP milestone awards.
create or replace function public.market_award_xp_event(
  p_user_id uuid,
  p_event_code text,
  p_xp integer
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  inserted_count integer := 0;
begin
  if p_xp <= 0 then
    return false;
  end if;

  insert into public.market_xp_events(user_id, event_code, xp_awarded)
  values (p_user_id, p_event_code, p_xp)
  on conflict (user_id, event_code) do nothing;

  get diagnostics inserted_count = row_count;

  if inserted_count = 0 then
    return false;
  end if;

  update public.profiles
  set xp = xp + p_xp
  where id = p_user_id;

  return true;
end;
$$;

-- Atomic buy RPC.
drop function if exists public.market_buy_player(text, text);
create or replace function public.market_buy_player(
  p_player_slug text,
  p_idempotency_key text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  market_status text;
  today_utc date := (now() at time zone 'UTC')::date;
  p public.market_portfolios;
  player_row public.market_players;
  holdings_count integer := 0;
  todays_buys integer := 0;
  duplicate_tx public.market_transactions;
  tx public.market_transactions;
  buy_value bigint := 0;
begin
  if uid is null then
    raise exception 'Not authenticated';
  end if;

  if coalesce(length(trim(p_idempotency_key)), 0) < 8 then
    raise exception 'Invalid idempotency key';
  end if;

  select market_settings.market_status into market_status
  from public.market_settings
  where singleton = true;

  if market_status is distinct from 'open' then
    raise exception 'Market is currently paused or updating';
  end if;

  select * into duplicate_tx
  from public.market_transactions
  where user_id = uid
    and idempotency_key = p_idempotency_key
  limit 1;

  if duplicate_tx.id is not null then
    perform public.market_ensure_portfolio(uid);
    perform public.market_recalculate_portfolio_totals(uid);
    return jsonb_build_object(
      'ok', true,
      'duplicate', true,
      'message', 'Duplicate request ignored',
      'transaction_id', duplicate_tx.transaction_id
    );
  end if;

  perform public.market_ensure_portfolio(uid);

  select * into p
  from public.market_portfolios
  where user_id = uid
  for update;

  select * into player_row
  from public.market_players
  where slug = p_player_slug
  for update;

  if player_row.id is null then
    raise exception 'Player not found';
  end if;

  if not player_row.active then
    raise exception 'Player is inactive';
  end if;

  buy_value := player_row.current_value;

  select count(*) into holdings_count
  from public.market_holdings
  where user_id = uid;

  if holdings_count >= 5 then
    raise exception 'Portfolio is full (maximum 5 players)';
  end if;

  if exists (
    select 1 from public.market_holdings
    where user_id = uid and player_id = player_row.id
  ) then
    raise exception 'Player already owned';
  end if;

  select count(*) into todays_buys
  from public.market_transactions
  where user_id = uid
    and trade_date_utc = today_utc
    and transaction_type = 'buy';

  if todays_buys >= 3 then
    raise exception 'Daily buy limit reached';
  end if;

  if p.available_balance < buy_value then
    raise exception 'Insufficient balance';
  end if;

  insert into public.market_holdings(
    user_id,
    player_id,
    acquisition_value,
    current_value_snapshot,
    unrealized_profit_loss
  )
  values (uid, player_row.id, buy_value, buy_value, 0);

  insert into public.market_transactions(
    user_id,
    player_id,
    transaction_type,
    execution_value,
    balance_before,
    balance_after,
    idempotency_key
  )
  values (
    uid,
    player_row.id,
    'buy',
    buy_value,
    p.available_balance,
    p.available_balance - buy_value,
    p_idempotency_key
  )
  returning * into tx;

  update public.market_portfolios
  set available_balance = p.available_balance - buy_value
  where user_id = uid;

  perform public.market_recalculate_portfolio_totals(uid);
  perform public.market_capture_snapshot(uid);

  perform public.market_award_xp_event(uid, 'market_first_buy', 25);

  select count(*) into holdings_count
  from public.market_holdings
  where user_id = uid;

  if holdings_count = 5 then
    perform public.market_award_xp_event(uid, 'market_first_full_portfolio', 50);
  end if;

  return jsonb_build_object(
    'ok', true,
    'duplicate', false,
    'message', 'Buy executed',
    'transaction_id', tx.transaction_id,
    'player_slug', player_row.slug,
    'execution_value', buy_value
  );
exception
  when unique_violation then
    if exists (
      select 1 from public.market_transactions
      where user_id = uid and idempotency_key = p_idempotency_key
    ) then
      return jsonb_build_object('ok', true, 'duplicate', true, 'message', 'Duplicate request ignored');
    end if;
    raise exception 'Buy blocked by uniqueness guard';
end;
$$;

-- Atomic sell RPC.
drop function if exists public.market_sell_player(text, text);
create or replace function public.market_sell_player(
  p_player_slug text,
  p_idempotency_key text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  market_status text;
  today_utc date := (now() at time zone 'UTC')::date;
  p public.market_portfolios;
  player_row public.market_players;
  holding_row public.market_holdings;
  todays_sales integer := 0;
  duplicate_tx public.market_transactions;
  tx public.market_transactions;
  sell_value bigint := 0;
  pnl bigint := 0;
begin
  if uid is null then
    raise exception 'Not authenticated';
  end if;

  if coalesce(length(trim(p_idempotency_key)), 0) < 8 then
    raise exception 'Invalid idempotency key';
  end if;

  select market_settings.market_status into market_status
  from public.market_settings
  where singleton = true;

  if market_status is distinct from 'open' then
    raise exception 'Market is currently paused or updating';
  end if;

  select * into duplicate_tx
  from public.market_transactions
  where user_id = uid
    and idempotency_key = p_idempotency_key
  limit 1;

  if duplicate_tx.id is not null then
    perform public.market_ensure_portfolio(uid);
    perform public.market_recalculate_portfolio_totals(uid);
    return jsonb_build_object(
      'ok', true,
      'duplicate', true,
      'message', 'Duplicate request ignored',
      'transaction_id', duplicate_tx.transaction_id
    );
  end if;

  perform public.market_ensure_portfolio(uid);

  select * into p
  from public.market_portfolios
  where user_id = uid
  for update;

  select * into player_row
  from public.market_players
  where slug = p_player_slug
  for update;

  if player_row.id is null then
    raise exception 'Player not found';
  end if;

  if not player_row.active then
    raise exception 'Player is inactive';
  end if;

  select * into holding_row
  from public.market_holdings
  where user_id = uid and player_id = player_row.id
  for update;

  if holding_row.id is null then
    raise exception 'Cannot sell: player not owned';
  end if;

  select count(*) into todays_sales
  from public.market_transactions
  where user_id = uid
    and trade_date_utc = today_utc
    and transaction_type = 'sell';

  if todays_sales >= 3 then
    raise exception 'Daily sell limit reached';
  end if;

  sell_value := player_row.current_value;
  pnl := sell_value - holding_row.acquisition_value;

  delete from public.market_holdings
  where id = holding_row.id;

  insert into public.market_transactions(
    user_id,
    player_id,
    transaction_type,
    execution_value,
    balance_before,
    balance_after,
    idempotency_key
  )
  values (
    uid,
    player_row.id,
    'sell',
    sell_value,
    p.available_balance,
    p.available_balance + sell_value,
    p_idempotency_key
  )
  returning * into tx;

  update public.market_portfolios
  set
    available_balance = p.available_balance + sell_value,
    realized_profit_loss = realized_profit_loss + pnl
  where user_id = uid;

  perform public.market_recalculate_portfolio_totals(uid);
  perform public.market_capture_snapshot(uid);

  if pnl > 0 then
    perform public.market_award_xp_event(uid, 'market_first_profitable_sale', 40);
  end if;

  return jsonb_build_object(
    'ok', true,
    'duplicate', false,
    'message', 'Sale executed',
    'transaction_id', tx.transaction_id,
    'player_slug', player_row.slug,
    'execution_value', sell_value,
    'profit_loss', pnl
  );
exception
  when unique_violation then
    if exists (
      select 1 from public.market_transactions
      where user_id = uid and idempotency_key = p_idempotency_key
    ) then
      return jsonb_build_object('ok', true, 'duplicate', true, 'message', 'Duplicate request ignored');
    end if;
    raise exception 'Sell blocked by uniqueness guard';
end;
$$;

-- Watchlist helper RPC.
drop function if exists public.market_toggle_watchlist(text);
create or replace function public.market_toggle_watchlist(p_player_slug text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  player_row public.market_players;
begin
  if uid is null then
    raise exception 'Not authenticated';
  end if;

  select * into player_row
  from public.market_players
  where slug = p_player_slug;

  if player_row.id is null then
    raise exception 'Player not found';
  end if;

  if exists (
    select 1 from public.market_watchlist
    where user_id = uid and player_id = player_row.id
  ) then
    delete from public.market_watchlist
    where user_id = uid and player_id = player_row.id;
    return jsonb_build_object('watchlisted', false);
  end if;

  insert into public.market_watchlist(user_id, player_id)
  values (uid, player_row.id)
  on conflict (user_id, player_id) do nothing;

  return jsonb_build_object('watchlisted', true);
end;
$$;

