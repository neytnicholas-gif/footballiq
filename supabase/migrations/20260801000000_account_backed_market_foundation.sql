-- Core player catalog (public-readable active rows only).
create table if not exists public.market_players (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  display_name text not null,
  short_name text,
  club_name text not null,
  position text not null check (position in ('GK','DEF','MID','FWD')),
  nationality text,
  active boolean not null default true,
  current_value bigint not null check (current_value >= 0),
  previous_value bigint not null check (previous_value >= 0),
  opening_season_value bigint not null check (opening_season_value >= 0),
  value_updated_at timestamptz not null default now(),
  data_updated_at timestamptz not null default now(),
  data_source_label text not null,
  source_reference text,
  provenance_status text not null default 'owner_seed_demo',
  owner_verified boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.player_season_stats (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.market_players(id) on delete cascade,
  season text not null,
  competition_label text not null,
  appearances integer,
  starts integer,
  minutes integer,
  goals integer,
  assists integer,
  clean_sheets integer,
  yellow_cards integer,
  red_cards integer,
  shots integer,
  shots_on_target integer,
  chances_created integer,
  key_passes integer,
  passes_completed integer,
  pass_accuracy numeric(5,2),
  tackles integer,
  interceptions integer,
  clearances integer,
  blocks integer,
  saves integer,
  goals_conceded integer,
  expected_goals numeric(6,3),
  expected_assists numeric(6,3),
  average_rating numeric(4,2),
  data_source text not null,
  source_reference text,
  provenance_status text not null default 'owner_seed_demo',
  owner_verified boolean not null default false,
  last_verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(player_id, season, competition_label)
);

create table if not exists public.market_portfolios (
  user_id uuid primary key references auth.users(id) on delete cascade,
  available_balance bigint not null default 100000000 check (available_balance >= 0),
  starting_balance bigint not null default 100000000 check (starting_balance > 0),
  portfolio_value bigint not null default 0 check (portfolio_value >= 0),
  total_account_value bigint not null default 100000000 check (total_account_value >= 0),
  realized_profit_loss bigint not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.market_holdings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  player_id bigint not null references public.market_players(id) on delete cascade,
  acquisition_value bigint not null check (acquisition_value >= 0),
  acquired_at timestamptz not null default now(),
  current_value_snapshot bigint not null check (current_value_snapshot >= 0),
  unrealized_profit_loss bigint not null default 0,
  unique(user_id, player_id)
);

create table if not exists public.market_transactions (
  id bigint generated by default as identity primary key,
  transaction_id text not null unique default ('mkt-' || substr(md5(random()::text || clock_timestamp()::text), 1, 16)),
  user_id uuid not null references auth.users(id) on delete cascade,
  player_id bigint not null references public.market_players(id) on delete restrict,
  transaction_type text not null check (transaction_type in ('buy', 'sell')),
  execution_value bigint not null check (execution_value >= 0),
  balance_before bigint not null check (balance_before >= 0),
  balance_after bigint not null check (balance_after >= 0),
  created_at timestamptz not null default now(),
  trade_date_utc date not null default ((now() at time zone 'UTC')::date),
  idempotency_key text not null,
  unique(user_id, idempotency_key)
);

create table if not exists public.market_value_history (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.market_players(id) on delete cascade,
  value bigint not null check (value >= 0),
  recorded_at timestamptz not null default now(),
  reason_category text not null,
  methodology_version text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.market_watchlist (
  user_id uuid not null references auth.users(id) on delete cascade,
  player_id bigint not null references public.market_players(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, player_id)
);

create table if not exists public.market_portfolio_snapshots (
  user_id uuid not null references auth.users(id) on delete cascade,
  snapshot_date date not null,
  available_balance bigint not null,
  portfolio_value bigint not null,
  total_account_value bigint not null,
  created_at timestamptz not null default now(),
  primary key (user_id, snapshot_date)
);

create table if not exists public.market_xp_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_code text not null,
  xp_awarded integer not null check (xp_awarded >= 0),
  created_at timestamptz not null default now(),
  unique(user_id, event_code)
);

create table if not exists public.market_settings (
  singleton boolean primary key default true check (singleton = true),
  market_status text not null default 'open' check (market_status in ('open', 'updating', 'paused')),
  methodology_version text not null default 'v1.0.0',
